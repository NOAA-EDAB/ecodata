#' Standardize wrangled indicator data prior to plotting
#'
#' Normalizes transformed indicator datasets into a consistent column schema
#' (`Time`, `Var`, `EPU`, `Source`, `Value`, `Units`, followed by any plot-specific
#' helper columns) before passing them into `ggplot2`. Handles both single
#' dataframes and named lists of dataframes for multi-layer or multi-source plots.
#'
#' @param data A `data.frame` (or `tibble`) of wrangled indicator data, or a named
#'   `list` of dataframes (e.g., `list(NEFSC = agg_bio, NEAMAP = neamap)`) when
#'   combining multiple data sources into a single plot.
#' @param var Character string. Fallback variable name to populate `Var` if the
#'   column was dropped during summarization. Default is `NULL`.
#' @param epu Character string or vector. Fallback Ecological Production Unit
#'   (`EPU`) value(s) to populate `EPU` if missing. Default is `NULL`.
#' @param units Character string. Fallback units string to populate `Units` if
#'   missing. Default is `NULL`.
#' @param value_col Character string. Name of the primary measurement column to
#'   rename to `"Value"` if `"Value"` is not already present (e.g., `"Mean"` or
#'   `"Forage_Mean"`). Default is `"Value"`.
#'
#' @return A standardized, ungrouped `data.frame` (or `tibble`) with canonical
#'   metadata columns ordered first, followed by any remaining auxiliary columns
#'   (such as `hline`, `upper`, `lower`, or `category`).
#'
#' @keywords internal
#'
#' @examples
#' \dontrun{
#' # Single-source standardization after summarization
#' fix <- ecodata::gsi |>
#'   dplyr::filter(Var == "gulf stream index") |>
#'   dplyr::mutate(Year = floor(Time)) |>
#'   dplyr::group_by(Year) |>
#'   dplyr::summarise(Value = mean(Value), .groups = "drop") |>
#'   dplyr::rename(Time = Year) |>
#'   format_plot_data(var = "gulf stream index", epu = "MAB")
#'
#' # Multi-source standardization
#' combined <- format_plot_data(
#'   list(NEFSC = dplyr::rename(agg_bio, Value = Mean), NEAMAP = neamap),
#'   epu = "MAB",
#'   units = "kg tow^-1"
#' )
#' }
format_plot_data <- function(
  data,
  var = NULL,
  epu = NULL,
  units = NULL,
  value_col = "Value"
) {
  # Handle multi-layer inputs (e.g., list(NEFSC = agg_bio, NEAMAP = neamap))
  if (is.list(data) && !is.data.frame(data)) {
    return(
      purrr::imap_dfr(data, function(df, source_name) {
        out <- format_plot_data(
          df,
          var = var,
          epu = epu,
          units = units,
          value_col = value_col
        )
        out$Source <- source_name
        out
      })
    )
  }

  df <- dplyr::ungroup(data)

  # Map custom value column (e.g., "Mean" or "Forage_Mean") to "Value" if needed
  if (!"Value" %in% names(df) && value_col %in% names(df)) {
    df <- dplyr::rename(df, Value = dplyr::all_of(value_col))
  }

  # Backfill standard metadata columns if dropped during summarization
  if (!"Var" %in% names(df) && !is.null(var)) {
    df$Var <- var
  }
  if (!"EPU" %in% names(df) && !is.null(epu)) {
    df$EPU <- epu
  }
  if (!"Units" %in% names(df) && !is.null(units)) {
    df$Units <- units
  }

  # Order canonical columns first, keeping plotting helpers (hline, upper, lower, etc.)
  core_cols <- intersect(
    c("Time", "Var", "EPU", "Source", "Value", "Units"),
    names(df)
  )
  dplyr::select(df, dplyr::all_of(core_cols), dplyr::everything())
}


#' Finalize plot output with optional data and trend statistics
#'
#' Centralizes the return structure across `ecodata` plotting functions. When both
#' `plotdata` and `trendStats` are `FALSE`, returns the `ggplot` object directly.
#' Otherwise, returns a named list containing the plot alongside the cleaned
#' underlying dataset and/or extracted long- and short-term trend model statistics.
#'
#' @param p A `ggplot` (or `ggarrange`) object generated by an `ecodata` plot function.
#' @param data Optional `data.frame` containing the standardized plot dataset
#'   (typically prepared via `format_plot_data()`). If `NULL` and `plotdata = TRUE`,
#'   falls back to `p$data`. Default is `NULL`.
#' @param plotdata Logical. If `TRUE`, includes the cleaned plot dataset in the
#'   returned list under `$data` (with internal plotting artifacts like `hline`
#'   removed). Default is `FALSE`.
#' @param trendStats Logical. If `TRUE`, extracts model fit statistics from `geom_gls`
#'   and `geom_lm` layers via `get_trend_stats()` and includes them in the
#'   returned list under `$stats`. Default is `FALSE`.
#' @param drop_cols Character vector of internal plotting-only column names to
#'   strip from the exported dataset when `plotdata = TRUE`. Default is `c("hline")`.
#'
#' @return If `plotdata = FALSE` and `trendStats = FALSE`, returns `p` directly.
#'   Otherwise, returns a named `list` containing:
#'   \describe{
#'     \item{plot}{The `ggplot` object `p`.}
#'     \item{data}{The standardized `data.frame` used to generate the plot (if `plotdata = TRUE`).}
#'     \item{stats}{A `data.frame` of long-term and short-term trend statistics (if `trendStats = TRUE`).}
#'   }
#'
#' @keywords internal
#'
#' @examples
#' \dontrun{
#' # At the end of a plot_* function:
#' return(finalize_plot(p, data = fix, plotdata = plotdata, trendStats = trendStats))
#' }
finalize_plot <- function(
  p,
  data = NULL,
  plotdata = FALSE,
  trendStats = FALSE,
  drop_cols = c("hline")
) {
  if (!plotdata && !trendStats) {
    return(p)
  }

  out <- list(plot = p)

  if (plotdata) {
    export_df <- if (!is.null(data)) data else p$data
    out$data <- dplyr::select(export_df, -dplyr::any_of(drop_cols))
  }

  if (trendStats) {
    out$stats <- get_trend_stats(p)
  }

  return(out)
}
